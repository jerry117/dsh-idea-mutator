import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const playwrightPath = process.env.BROWSER_NODE_MODULES ? require.resolve('playwright', { paths: [process.env.BROWSER_NODE_MODULES] }) : 'playwright';
const { chromium } = require(playwrightPath);
const url = process.env.PREVIEW_URL || 'http://127.0.0.1:4173';
const output = new URL('../artifacts/', import.meta.url).pathname;
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.locator('.mutation-card').last().waitFor();
  await page.screenshot({ path: output + 'desktop.png', fullPage: true });
  await page.locator('#mutate').click();
  assert.equal(await page.locator('#input-error').isVisible(), true);
  await page.getByRole('button', { name: '一款微信小游戏', exact: true }).click();
  assert.ok((await page.locator('#idea').inputValue()).includes('微信小游戏'));
  await page.locator('.mutation-card').first().click();
  const locked = await page.locator('.mutation-card.locked .card-name').textContent();
  await page.locator('#shuffle').click();
  assert.equal(await page.locator('.mutation-card.locked .card-name').textContent(), locked);
  await page.locator('#mutate').click();
  await page.locator('#result').waitFor({ state: 'visible' });
  assert.equal(await page.locator('.field-text').count(), 5);
  await page.locator('#result-title').fill('我的一分钟小游戏实验');
  await page.locator('#section-1').fill('先让三位朋友试玩，记录他们是否主动再来一局。');
  await page.locator('#save').click();
  assert.equal(await page.locator('#saved-count').textContent(), '1');
  await page.reload();
  assert.equal(await page.locator('#result-title').inputValue(), '我的一分钟小游戏实验');
  assert.equal(await page.locator('#section-1').inputValue(), '先让三位朋友试玩，记录他们是否主动再来一局。');
  await page.locator('#copy').click();
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(clipboard.includes('我的一分钟小游戏实验'));
  assert.ok(clipboard.includes('先让三位朋友试玩'));
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), '我的一分钟小游戏实验.md');
  await download.saveAs(output + download.suggestedFilename());
  await page.locator('#deepen').click();
  assert.ok((await page.evaluate(() => navigator.clipboard.readText())).includes('尚未经过事实验证'));
  await page.locator('[data-view="collection"]').click();
  assert.equal(await page.locator('.history-card').count(), 1);
  await page.getByRole('button', { name: '继续编辑 ↗', exact: true }).click();
  assert.equal(await page.locator('#result-title').inputValue(), '我的一分钟小游戏实验');
  await page.screenshot({ path: output + 'result.png', fullPage: true });
  await page.locator('#deck-toggle').click();
  assert.equal(await page.locator('.deck-choice').count(), 12);
  await page.locator('[data-count="1"]').click();
  assert.equal(await page.locator('.mutation-card').count(), 1);
  await page.locator('[data-count="3"]').click();
  // Drag a text file through the actual drop handler.
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer();
    data.items.add(new File(['一个可以分享给朋友的新玩法'], 'idea.md', { type: 'text/markdown' }));
    return data;
  });
  await page.locator('#dropzone').dispatchEvent('drop', { dataTransfer: transfer });
  await page.waitForFunction(() => document.querySelector('#idea').value === '一个可以分享给朋友的新玩法');
  // Imported markup remains inert plain text, including in history cards.
  await page.locator('#idea').fill('<img src=x onerror="window.XSS=1"> 一个点子');
  await page.locator('#mutate').click();
  await page.waitForFunction(() => document.querySelector('#mutation-count').textContent === '2');
  assert.equal(await page.evaluate(() => window.XSS), undefined);
  await page.locator('[data-view="collection"]').click();
  await page.locator('[data-filter="all"]').click();
  assert.equal(await page.locator('.history-card').count(), 2);
  assert.equal(await page.locator('.history-card img').count(), 0);
  await page.locator('.history-delete').first().click();
  assert.equal(await page.locator('.history-card').count(), 1);
  // Clean mobile context, preserving independent local storage.
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const phone = await mobile.newPage();
  phone.on('pageerror', error => errors.push(error.message));
  await phone.goto(url);
  await phone.locator('.mutation-card').last().waitFor();
  const layout = await phone.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth }));
  assert.ok(layout.width <= layout.viewport, `Mobile overflow: ${JSON.stringify(layout)}`);
  await phone.screenshot({ path: output + 'mobile.png', fullPage: true });
  await phone.getByRole('button', { name: '一款微信小游戏', exact: true }).click();
  await phone.locator('#mutate').click();
  await phone.locator('#result').waitFor({ state: 'visible' });
  assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await phone.screenshot({ path: output + 'mobile-result.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile layouts, validation, locked cards, generation, editable drafts, persistence, collection, clipboard, Markdown export, DSH prompt, card library, file drops, inert imports, deletion.');
  console.log(`Screenshots: ${output}`);
} finally { await browser.close(); }
